#!/usr/bin/env python3
"""Generate a book's `_meta.typ` from its `book.toml`.

`book.toml` is the single source of truth for metadata; the generated Typst
file is committed so that a bare `typst compile` keeps working, and `check`
fails when the two drift apart.
"""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANNER = "// AUTO-GENERATED by scripts/gen_meta.py from book.toml — do not edit.\n"


def _squash(value: str) -> str:
    return " ".join(value.split())


def _typst_string(value: str) -> str:
    escaped = _squash(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "(" + ", ".join(_typst_string(str(v)) for v in value) + ",)"
    return _typst_string(str(value))


def render_meta(book_dir: Path) -> str:
    book_dir = book_dir.resolve()
    with (book_dir / "book.toml").open("rb") as fh:
        data = tomllib.load(fh)

    book = data["book"]
    license_ = data.get("license", {})
    fields = {
        "slug": book["slug"],
        "title": book["title"],
        "subtitle": book.get("subtitle", ""),
        "title_en": book.get("title_en", ""),
        "author": book.get("author", "Niubook"),
        "series": book.get("series", "Niubook"),
        "short_title": book.get("short_title", book["title"]),
        "language": book.get("language", "zh-CN"),
        "year": book.get("year", 2026),
        "edition": book.get("edition", ""),
        "version": book.get("version", "0.0.0"),
        "status": book.get("status", "draft"),
        "audience": book.get("audience", ""),
        "knowledge_cutoff": book.get("knowledge_cutoff", ""),
        "cover_note": book.get("cover_note", ""),
        "abstract": book.get("abstract", ""),
        "tags": book.get("tags", []),
        "license_spdx": license_.get("spdx", ""),
        "license_name": license_.get("name", ""),
        "license_url": license_.get("url", ""),
    }

    lines = [BANNER, "#let meta = (\n"]
    for key, value in fields.items():
        lines.append(f"  {key}: {_value(value)},\n")
    lines.append(")\n")
    return "".join(lines)


def write_meta(book_dir: Path) -> Path:
    target = book_dir / "_meta.typ"
    target.write_text(render_meta(book_dir), encoding="utf-8")
    return target


def main(argv: list[str]) -> int:
    if not argv:
        print("usage: gen_meta.py <book-dir> [--write|--check]", file=sys.stderr)
        return 2
    book_dir = Path(argv[0])
    if not book_dir.is_absolute():
        book_dir = (Path.cwd() / book_dir).resolve()
    target = book_dir / "_meta.typ"
    rendered = render_meta(book_dir)

    if "--check" in argv:
        if not target.exists():
            print(f"missing {target}", file=sys.stderr)
            return 1
        if target.read_text(encoding="utf-8") != rendered:
            print(f"{target} is out of date; run `just meta {book_dir.name}`", file=sys.stderr)
            return 1
        print(f"ok {target.relative_to(ROOT)}")
        return 0

    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
